#!/usr/bin/env python3
"""Regenerate the two all-step restoration tables from verified frozen values.

Run from any directory. No experiment, estimator, interval, or support is changed.
Original readouts and scalars accompany the r11_allstep_* data files; the full
source verification is documented in the author audit.
"""
import json
from pathlib import Path

MANUSCRIPT = Path(__file__).resolve().parents[1]
data = json.loads((MANUSCRIPT / "plot_sources/data/r11_allstep_restoration_verified.json").read_text())
comparisons = data["comparisons"]
arm_results = data["arms"]
FAMILIES = ("Camera Viewpoints", "Sensor Noise")
ARMS = ("N_C", "N_T", "R_resp", "R_clean", "R_rand", "R_full")


def tex_arm(arm):
    prefix, suffix = arm.split("_")
    return "$" + prefix + "_{\\mathrm{" + suffix + "}}$"


contrast_lines = [
    "% Generated by plot_sources/build_allstep_restoration_tables.py from verified original values.",
    "\\begin{table*}[t]",
    "\\centering\\small",
    "\\setlength{\\tabcolsep}{7pt}",
    "\\begin{tabular}{@{}llrr@{}}",
    "\\toprule",
    "Family & Comparator & Translation gain $G_{f,b}$ [simultaneous interval] & Success gain (pp) [simultaneous interval]\\\\",
    "\\midrule",
]
for i, row in enumerate(comparisons):
    if i == 3:
        contrast_lines.append("\\midrule")
    family = "Camera" if row["family"] == FAMILIES[0] else "Sensor"
    lo, hi = row["command_simultaneous_interval"]
    slo, shi = row["success_simultaneous_interval_pp"]
    contrast_lines.append(f"{family} & {tex_arm(row['comparator'])} & ${row['command_gain']:.4f}\\;[{lo:.4f},{hi:.4f}]$ & ${row['success_gain_pp']:+.2f}\\;[{slo:.2f},{shi:.2f}]$\\\\")
contrast_lines += [
    "\\bottomrule",
    "\\end{tabular}",
    "\\caption{\\textbf{Complete confirmation comparisons for all-step response restoration.} Each row compares $R_{\\mathrm{resp}}$ with the stated comparator. Positive translation gain means smaller initial issued-translation error relative to the paired native-clean plan; gains use a fixed family scale $S_f$. Positive success gain means greater task completion. Each endpoint has its own six-comparison family of simultaneous 95\\% whole-task bootstrap intervals. Camera: 27 tasks, 48 settings and 96 paired noise cases; Sensor: 30 tasks, 60 settings and 120 pairs. All six command intervals are positive. Every success interval includes zero, with the Sensor--clean lower endpoint equal to zero.}",
    "\\label{tab:allstep-restoration-contrasts}",
    "\\end{table*}",
]
(MANUSCRIPT / "sections/table_allstep_restoration_contrasts.tex").write_text("\n".join(contrast_lines)+"\n")

arm_lines = [
    "% Generated by plot_sources/build_allstep_restoration_tables.py from verified original values.",
    "\\begin{table*}[t]",
    "\\centering\\small",
    "\\setlength{\\tabcolsep}{9pt}",
    "\\begin{tabular}{@{}lrrrrrr@{}}",
    "\\toprule",
    " & \\multicolumn{3}{c}{Camera Viewpoints} & \\multicolumn{3}{c}{Sensor Noise}\\\\",
    "\\cmidrule(lr){2-4}\\cmidrule(l){5-7}",
    "Arm & Error $e$ & Success (\\%) & Edit sum ($10^3$) & Error $e$ & Success (\\%) & Edit sum ($10^3$)\\\\",
    "\\midrule",
]
for arm in ARMS:
    cells = []
    for family in FAMILIES:
        row = next(x for x in arm_results if x["family"] == family and x["arm"] == arm)
        cells += [f"{row['q0_translation_error']:.4f}", f"{row['success_percent']:.2f}", f"{row['cumulative_actual_token_L2']/1000:.2f}"]
    arm_lines.append(tex_arm(arm)+" & "+" & ".join(cells)+"\\\\")
arm_lines += [
    "\\bottomrule",
    "\\end{tabular}",
    "\\caption{\\textbf{All six arms and their observed edit exposure.} Task-equal descriptive means on the same confirmation support. $e$ is the Euclidean error over the fifteen initial issued translation coordinates, in adapter command units. The native-clean error is zero by definition. Edit sum is the cumulative sum of actual post-cast tokenwise $\\ell_2$ writes over every generated query of each arm's own episode; it varies with both the write and the trajectory length. Response, clean and random arms share rank, coefficient and schedule, while their actual edit magnitudes differ. Full-$H$ restoration supplies a separate reference intervention.}",
    "\\label{tab:allstep-restoration-arms}",
    "\\end{table*}",
]
(MANUSCRIPT / "sections/table_allstep_restoration_arms.tex").write_text("\n".join(arm_lines)+"\n")

print("Regenerated both all-step restoration tables from frozen values.")
